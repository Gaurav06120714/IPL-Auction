#!/usr/bin/env node
/**
 * sync-player-photos.js
 * ---------------------------------------------------------------------------
 * Downloads IPL player photos from a Google Drive folder named "IPL Player Photos",
 * matches each file to a player in the database, converts/optimizes to JPG, and
 * stores them LOCALLY under frontend/public/images/players/.
 *
 * It then regenerates:
 *   - frontend/src/data/player-images.ts          (name -> local path map)
 *   - frontend/public/images/players/missing-photos.json
 *
 * Photos are served from local files only — no external URLs at runtime, so the
 * app keeps working offline after a sync.
 *
 * USAGE
 *   npm run sync:players
 *
 * AUTH (Google Drive read-only). Provide ONE of:
 *   - GOOGLE_APPLICATION_CREDENTIALS=/path/to/service-account.json
 *       (share the "IPL Player Photos" folder with the service account email)
 *   - GOOGLE_OAUTH_TOKEN=/path/to/authorized_user.json
 *
 * DEPENDENCIES (install once at repo root):
 *   npm i -D googleapis sharp
 *
 * The script degrades gracefully: if deps or credentials are missing it still
 * regenerates the mapping and missing-photos.json from whatever is already on disk,
 * and prints clear setup instructions instead of failing the build.
 * ---------------------------------------------------------------------------
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SEED = path.join(ROOT, "backend/src/db/seed.ts");
const OUT_DIR = path.join(ROOT, "frontend/public/images/players");
const MAP_FILE = path.join(ROOT, "frontend/src/data/player-images.ts");
const MISSING_FILE = path.join(OUT_DIR, "missing-photos.json");
const DRIVE_FOLDER_NAME = "IPL Player Photos";

const log = (...a) => console.log("[sync:players]", ...a);

function slugify(name) {
  return name
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/** Read the canonical player list straight from the DB seed file. */
function loadPlayers() {
  const src = fs.readFileSync(SEED, "utf8");
  return [...src.matchAll(/name:\s*"([^"]+)"/g)].map((m) => m[1]);
}

function ensureDirs() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.mkdirSync(path.dirname(MAP_FILE), { recursive: true });
}

/** Regenerate the TS mapping + missing-photos.json from current disk state. */
function regenerateArtifacts(players) {
  const entries = players
    .map((n) => `  ${JSON.stringify(n)}: "/images/players/${slugify(n)}.jpg",`)
    .join("\n");

  const ts = `// AUTO-GENERATED by scripts/sync-player-photos.js — do not edit by hand.
// Maps each player name to its LOCAL photo path under public/images/players/.
// Photos load from local files only — no external URLs at runtime.
// If a file is absent, <PlayerCard> falls back to a generated avatar, then initials.

export const PLAYER_IMAGES: Record<string, string> = {
${entries}
};

/** Filename-safe slug, e.g. "AB de Villiers" -> "ab-de-villiers". Mirrors the sync script. */
export function playerSlug(name: string): string {
  return name
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\\u0300-\\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/** Resolve a player's local photo path. Returns the mapped path or a slug-derived default. */
export function getPlayerImage(name: string): string {
  return PLAYER_IMAGES[name] ?? \`/images/players/\${playerSlug(name)}.jpg\`;
}
`;
  fs.writeFileSync(MAP_FILE, ts);

  const missing = players.filter(
    (n) => !fs.existsSync(path.join(OUT_DIR, `${slugify(n)}.jpg`))
  );
  fs.writeFileSync(MISSING_FILE, JSON.stringify(missing, null, 2) + "\n");
  return missing;
}

function tryRequire(name) {
  try {
    return require(name);
  } catch {
    return null;
  }
}

function getAuth(google) {
  const scopes = ["https://www.googleapis.com/auth/drive.readonly"];
  if (process.env.GOOGLE_APPLICATION_CREDENTIALS) {
    return new google.auth.GoogleAuth({ scopes }).getClient();
  }
  if (process.env.GOOGLE_OAUTH_TOKEN) {
    const creds = JSON.parse(fs.readFileSync(process.env.GOOGLE_OAUTH_TOKEN, "utf8"));
    const oauth = new google.auth.OAuth2(creds.client_id, creds.client_secret);
    oauth.setCredentials(creds);
    return Promise.resolve(oauth);
  }
  return null;
}

async function syncFromDrive(players) {
  const googleapis = tryRequire("googleapis");
  const sharp = tryRequire("sharp");

  if (!googleapis || !sharp) {
    log("⚠ Optional deps missing. Install with:  npm i -D googleapis sharp");
    log("  Skipping Drive download; regenerating local artifacts only.");
    return { downloaded: 0, skipped: true };
  }

  const { google } = googleapis;
  const authPromise = getAuth(google);
  if (!authPromise) {
    log("⚠ No Google credentials found.");
    log("  Set GOOGLE_APPLICATION_CREDENTIALS or GOOGLE_OAUTH_TOKEN, then re-run.");
    log("  Skipping Drive download; regenerating local artifacts only.");
    return { downloaded: 0, skipped: true };
  }

  const auth = await authPromise;
  const drive = google.drive({ version: "v3", auth });

  // Locate the "IPL Player Photos" folder.
  const folderRes = await drive.files.list({
    q: `name = '${DRIVE_FOLDER_NAME}' and mimeType = 'application/vnd.google-apps.folder' and trashed = false`,
    fields: "files(id, name)",
    pageSize: 5,
  });
  const folder = folderRes.data.files && folderRes.data.files[0];
  if (!folder) {
    log(`⚠ Drive folder "${DRIVE_FOLDER_NAME}" not found (or not shared with these credentials).`);
    return { downloaded: 0, skipped: true };
  }
  log(`Found Drive folder "${DRIVE_FOLDER_NAME}" (${folder.id}).`);

  // Index players by slug for filename matching.
  const bySlug = new Map(players.map((n) => [slugify(n), n]));

  // List all images in the folder (paginated).
  let pageToken;
  const driveFiles = [];
  do {
    const res = await drive.files.list({
      q: `'${folder.id}' in parents and mimeType contains 'image/' and trashed = false`,
      fields: "nextPageToken, files(id, name, mimeType)",
      pageSize: 200,
      pageToken,
    });
    driveFiles.push(...(res.data.files || []));
    pageToken = res.data.nextPageToken;
  } while (pageToken);

  log(`Drive folder has ${driveFiles.length} image(s).`);

  let downloaded = 0;
  for (const f of driveFiles) {
    const base = f.name.replace(/\.[^.]+$/, "");
    const fileSlug = slugify(base);
    const matched = bySlug.get(fileSlug);
    if (!matched) {
      log(`  · skip "${f.name}" — no matching player`);
      continue;
    }
    const dest = path.join(OUT_DIR, `${slugify(matched)}.jpg`);
    const buf = await drive.files.get(
      { fileId: f.id, alt: "media" },
      { responseType: "arraybuffer" }
    );
    // Convert to JPG, square cover crop, sensible max size.
    await sharp(Buffer.from(buf.data))
      .resize(512, 512, { fit: "cover", position: "attention" })
      .jpeg({ quality: 86, mozjpeg: true })
      .toFile(dest);
    downloaded++;
    log(`  ✓ ${matched}  ->  ${path.basename(dest)}`);
  }
  return { downloaded, skipped: false };
}

(async function main() {
  log("Starting player photo sync…");
  ensureDirs();
  const players = loadPlayers();
  log(`Players in database: ${players.length}`);

  let result = { downloaded: 0, skipped: true };
  try {
    result = await syncFromDrive(players);
  } catch (err) {
    log("⚠ Drive sync error:", err.message);
    log("  Regenerating local artifacts from existing files.");
  }

  const missing = regenerateArtifacts(players);

  log("──────────────────────────────────────────");
  log(`Downloaded this run : ${result.downloaded}`);
  log(`Photos present      : ${players.length - missing.length}/${players.length}`);
  log(`Photos missing      : ${missing.length}`);
  log(`Mapping             : ${path.relative(ROOT, MAP_FILE)}`);
  log(`Missing report      : ${path.relative(ROOT, MISSING_FILE)}`);
  log("Done.");
})();
